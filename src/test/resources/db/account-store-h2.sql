-- PostgreSQL-specific JSONB assertions remain in BatchPostgresApiTests.
create domain if not exists jsonb as varchar;

create table if not exists batch_outbox (
    batch_id uuid not null,
    processed boolean not null default false,
    constraint batch_outbox_pkey primary key (batch_id)
);

create table if not exists accounts (
    id bigint generated by default as identity primary key,
    batch_id uuid not null,
    account_number varchar(25) not null,
    product_code varchar(25) not null,
    branch_code varchar(25) not null,
    pricing_date date not null,
    constraint fk_accounts_batch foreign key (batch_id) references batch_outbox (batch_id),
    constraint uk_accounts_batch_account_number unique (batch_id, account_number)
);

create table if not exists account_attributes (
    id bigint generated by default as identity primary key,
    account_id bigint not null,
    code varchar(25) not null,
    value jsonb not null,
    constraint fk_account_attributes_account foreign key (account_id) references accounts (id)
);

create table if not exists fee_requests (
    id bigint generated by default as identity primary key,
    account_id bigint not null,
    fee_request_id bigint not null,
    code varchar(25) not null,
    transaction_amount numeric(1000, 100),
    constraint fk_fee_requests_account foreign key (account_id) references accounts (id),
    constraint uk_fee_requests_account_fee_request_id unique (account_id, fee_request_id),
    constraint chk_fee_requests_transaction_amount
        check (transaction_amount >= 0 and mod(transaction_amount, 0.01) = 0)
);
